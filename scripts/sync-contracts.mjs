// Copies ABIs (forge out/) and deployment addresses into packages/shared so web and api share one source.
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const contracts = ["OnTopLaunchpad", "OnTopHook", "OnTopRouter", "OnTopDistributor", "OnTopToken"];

let out = "// generated by scripts/sync-contracts.mjs — do not edit\n\n";
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(`${root}contracts/out/${name}.sol/${name}.json`, "utf8"));
  out += `export const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
writeFileSync(`${root}packages/shared/src/abi.generated.ts`, out);

const deployments = {};
for (const network of ["testnet", "mainnet"]) {
  const file = `${root}contracts/deployments/${network}.json`;
  if (existsSync(file)) deployments[network] = JSON.parse(readFileSync(file, "utf8"));
}
writeFileSync(
  `${root}packages/shared/src/deployments.generated.ts`,
  `// generated by scripts/sync-contracts.mjs — do not edit\n\nexport const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log(`synced ${contracts.length} ABIs, deployments: ${Object.keys(deployments).join(", ")}`);
